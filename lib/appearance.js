function genderKey(g) {
  var s = String(g || '');
  if (s.indexOf('여') >= 0 || /^f/i.test(s)) return 'f';
  return 'm';   // 미지정·남성 → m (실제 주문의 대다수가 남성 배우자 조회)
}

