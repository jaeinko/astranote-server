/* 도수대(데칸) — 같은 별자리라도 강도가 다르다. 손님이 "그 사람 맞다" 하게 만드는 미세 조정 */
function decanNote(deg) {
  var d = parseFloat(deg);
  if (d < 10)  return '앞 도수(0~10도)라 그 별자리의 특징이 가장 날것으로, 순도 높게 드러난다';
  if (d < 20)  return '가운데 도수(10~20도)라 특징이 안정적으로 굳어 있다. 극단적이지 않고 균형 잡힌 형태다';
  return '뒤 도수(20~30도)라 다음 별자리의 기운이 섞인다. 전형적인 모습에서 한 발 비껴 있다';
}

function signIndexOf(abs) { return Math.floor((((abs % 360) + 360) % 360) / 30); }

function wholeSignHouse(abs, ascAbs) {
  return ((signIndexOf(abs) - signIndexOf(ascAbs)) % 12 + 12) % 12 + 1;
}

/**
 * 얼굴상 판정 — 코드가 정하고 모델은 받아쓴다.
 * @return {{label:String, main:String, sub:String|null, vibes:String[],
 *           gap:String[], scent:String, basis:String, mode:'spouse'|'attraction'}|null}
 */
function buildFaceType(planets, asc, targetGender) {
  if (!planets) return null;
  var gk = genderKey(targetGender);

  /* 출생시각 미상 → 7하우스가 없다. 금성 별자리로 '끌리는 얼굴상'만 판정한다. */
  if (!asc) {
    var v = planets['금성'];
    if (!v || !FACE[v.sign]) return null;
    var fv = FACE[v.sign][gk];
    return {
      label: fv.main + ' 취향', main: fv.main, sub: null,
      vibes: fv.vibe.slice(), gap: GAP[v.sign].slice(), scent: SCENT[v.sign],
      basis: '금성 ' + v.sign, mode: 'attraction'
    };
  }

  var dscSign = SIGNS_KR[signIndexOf((asc.abs + 180) % 360)];
  var base = FACE[dscSign][gk];
  var sub = null, label = base.main;

  var inSeventh = BUFF_ORDER.filter(function (n) {
    return planets[n] && wholeSignHouse(planets[n].abs, asc.abs) === 7;
  });
  /* 버프가 메인상과 같은 말을 반복하면(냉미남 고양이상 × 냉미남 버프) 다음 행성으로 넘긴다 */
  var buffs = inSeventh.map(function (n) { return PLANET_BUFF[n][gk]; })
    .filter(function (b) { return base.main.indexOf(b.split(' ')[0]) < 0; });
  if (inSeventh.length && !buffs.length) {
    sub = '순도 100%';
    label = '순도 100% ' + base.main;
  } else if (buffs.length) {
    sub = buffs[0];
    label = base.main + ' × ' + sub;
  } else {
    var r = planets[RULER[dscSign]];
    if (r && FACE[r.sign]) {
      var rf = FACE[r.sign][gk];
      /* 같은 동물이 겹치면 섞을 게 없다 — 그건 '순도'로 판다 */
      var stem = base.main.replace(/^(냉미남|냉미녀) /, '').replace(/상$/, '');
      if (rf.main === base.main || rf.eye.indexOf(stem) >= 0) {
        sub = '순도 100%';
        label = '순도 100% ' + base.main;
      } else {
        sub = rf.eye;
        label = base.main + ' × ' + sub;
      }
    }
  }

  return {
    label: label, main: base.main, sub: sub,
    vibes: base.vibe.slice(), gap: GAP[dscSign].slice(), scent: SCENT[dscSign],
    basis: '7하우스 ' + dscSign, mode: 'spouse'
  };
}

